def add_translations_to_po(po_filepath, translations_dict):
    """Añade traducciones al archivo .po"""
    import codecs
    
    def parse_quoted_block(lines, start_index):
        """Parse a block starting at a msgid/msgstr line and return text + raw lines."""
        raw_lines = [lines[start_index]]
        line = lines[start_index]
        if line.startswith('msgid') or line.startswith('msgstr'):
            if line.endswith('"') and not line == 'msgid ""' and not line == 'msgstr ""':
                text = line.split('"', 1)[1][:-1]
                return text, raw_lines, start_index + 1
            text = ''
            i = start_index + 1
            while i < len(lines) and lines[i].startswith('"'):
                raw_lines.append(lines[i])
                text += lines[i].strip()[1:-1]
                i += 1
            return text, raw_lines, i
        return '', raw_lines, start_index + 1
    
    try:
        with codecs.open(po_filepath, 'r', encoding='utf-8') as f:
            lines = f.read().split('\n')
        
        new_lines = []
        i = 0
        while i < len(lines):
            line = lines[i]

            if line.startswith('msgid'):
                msgid_text, msgid_block, next_index = parse_quoted_block(lines, i)
                i = next_index

                # Collect the msgstr block if present
                msgstr_text = ''
                msgstr_block = []
                if i < len(lines) and lines[i].startswith('msgstr'):
                    msgstr_text, msgstr_block, next_index = parse_quoted_block(lines, i)
                    i = next_index
                
                # Copy original msgid block first
                new_lines.extend(msgid_block)

                # If we have a translation, replace msgstr block
                if msgid_text in translations_dict:
                    translation = translations_dict[msgid_text]
                    if '\n' in translation:
                        new_lines.append('msgstr ""')
                        for part in translation.split('\n'):
                            new_lines.append(f'"{part}"')
                    else:
                        new_lines.append(f'msgstr "{translation}"')
                else:
                    new_lines.extend(msgstr_block)
                continue

            new_lines.append(line)
            i += 1

        with codecs.open(po_filepath, 'w', encoding='utf-8') as f:
            f.write('\n'.join(new_lines))
        
        print(f"[OK] Traducido: {po_filepath}")
        return True
    except Exception as e:
        print(f"[ERROR] Error en {po_filepath}: {e}")
        return False

